// Holt die Liste aller Google-Fonts-Familien und schreibt sie nach src/data/googleFonts.ts.
//
//   npm run fetch:google-fonts
//
// Die Liste reist in der App mit, statt zur Laufzeit geholt zu werden: Die Stile-Seite fragt sonst
// bei jedem Öffnen das Netz, und ohne Netz gäbe es gar keine Vorschläge. Veraltet ist sie höchstens
// um die Familien, die Google seitdem neu aufgenommen hat — und ein Name, der nicht in der Liste
// steht, lässt sich weiter eintippen.
//
// Quelle ist dieselbe Datei, aus der fonts.google.com seine eigene Liste baut. Sortiert nach
// Googles Beliebtheitsrang, damit die ungefilterte Liste mit den Schriften beginnt, die man sucht.
import fs from 'node:fs'
import path from 'node:path'

const URL = 'https://fonts.google.com/metadata/fonts'
const ZIEL = path.join(import.meta.dirname, '../src/data/googleFonts.ts')

const KATEGORIE = {
  'Sans Serif': 'sans-serif',
  Serif: 'serif',
  Monospace: 'monospace',
  Display: 'display',
  Handwriting: 'handwriting'
}

const antwort = await fetch(URL)
if (!antwort.ok) {
  console.error(`${URL}: HTTP ${antwort.status}`)
  process.exit(1)
}
// Die Antwort beginnt mit dem Schutzpräfix `)]}'`, das JSON-Hijacking verhindert.
const daten = JSON.parse((await antwort.text()).replace(/^\)\]\}'\s*/, ''))
const familien = daten.familyMetadataList
  .slice()
  .sort((a, b) => a.popularity - b.popularity || a.family.localeCompare(b.family))

const unbekannt = [...new Set(familien.map((f) => f.category).filter((c) => !(c in KATEGORIE)))]
if (unbekannt.length > 0) {
  console.error(`Unbekannte Kategorie(n): ${unbekannt.join(', ')} — KATEGORIE in diesem Skript ergänzen.`)
  process.exit(1)
}

const heute = new Date().toISOString().slice(0, 10)
const literal = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const zeilen = familien.map((f) => `  [${literal(f.family)}, '${KATEGORIE[f.category]}'],`)
const inhalt = `// Generated by scripts/fetch-google-fonts.mjs - do not edit by hand, run \`npm run fetch:google-fonts\`.
//
// Every family Google Fonts serves, most popular first, with the category fonts.google.com files
// it under. Quartz asks Google's CSS2 API for whatever name stands in theme.typography, so a name
// that is missing here (a family added after ${heute}) still works when typed; the list is a
// typing aid and a spelling check, not a gate.
export type GoogleFontCategory = 'sans-serif' | 'serif' | 'monospace' | 'display' | 'handwriting'

export const GOOGLE_FONTS_FETCHED = '${heute}'

export const GOOGLE_FONTS: readonly (readonly [string, GoogleFontCategory])[] = [
${zeilen.join('\n')}
]
`
fs.writeFileSync(ZIEL, inhalt)
console.log(`${familien.length} Familien nach ${path.relative(process.cwd(), ZIEL)} geschrieben (Stand ${heute}).`)
